    ("monthly-second-tuesday", "DTSTART:20240101T090000Z\nRRULE:FREQ=MONTHLY;BYDAY=2TU;COUNT=6"),
    ("yearly-leap-day", "DTSTART:20240229T090000Z\nRRULE:FREQ=YEARLY;BYMONTH=2;BYMONTHDAY=29;COUNT=5"),
